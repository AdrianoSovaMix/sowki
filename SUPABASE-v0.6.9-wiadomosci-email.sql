on public.message_recipients
for select
to authenticated
using (private.is_sowki_admin());

drop policy if exists "sowki_admin_insert_message_recipients" on public.message_recipients;
create policy "sowki_admin_insert_message_recipients"
on public.message_recipients
for insert
to authenticated
with check (private.is_sowki_admin());

drop policy if exists "sowki_admin_update_message_recipients" on public.message_recipients;
create policy "sowki_admin_update_message_recipients"
on public.message_recipients
for update
to authenticated
using (private.is_sowki_admin())
with check (private.is_sowki_admin());

drop policy if exists "sowki_admin_delete_message_recipients" on public.message_recipients;
create policy "sowki_admin_delete_message_recipients"
on public.message_recipients
for delete
to authenticated
using (private.is_sowki_admin());

