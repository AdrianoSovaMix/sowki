create table if not exists public.message_recipients (
  id bigint generated by default as identity primary key,
  display_name text not null,
  role text,
  email text not null,
  active boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint message_recipients_name_len check (char_length(display_name) between 1 and 120),
  constraint message_recipients_role_len check (role is null or char_length(role) <= 120),
  constraint message_recipients_email_len check (char_length(email) between 3 and 254)
);

create unique index if not exists message_recipients_email_unique
on public.message_recipients (lower(email));

alter table public.message_recipients enable row level security;

revoke all on public.message_recipients from anon;
revoke all on public.message_recipients from authenticated;

grant select, insert, update, delete
on public.message_recipients
to authenticated;

drop policy if exists "sowki_admin_read_message_recipients" on public.message_recipients;
